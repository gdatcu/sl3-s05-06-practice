public class ForLoopExample {
    public static void main(String[] args) {
        System.out.println("Incepe numaratoarea:");

        int i;
        for (i = 10; i >= 0; i++) {
            System.out.println("Numarul este: " + i);

        }

        System.out.println("Valoare finala a lui i: " + i);
    }
}